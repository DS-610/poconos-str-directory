const https = require('https');

const SB_TOKEN = process.env.SUPABASE_ACCESS_TOKEN || process.argv[2];
const PROJECT_ID = process.env.SUPABASE_PROJECT_ID || 'ykaxmqmxizxnenebyger';

function runSQL(query) {
  return new Promise((resolve, reject) => {
    const data = JSON.stringify({ query });
    const options = {
      hostname: 'api.supabase.com',
      path: `/v1/projects/${PROJECT_ID}/database/query`,
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${SB_TOKEN}`,
        'Content-Type': 'application/json',
        'Content-Length': Buffer.byteLength(data),
      },
    };
    const req = https.request(options, (res) => {
      let body = '';
      res.on('data', (chunk) => body += chunk);
      res.on('end', () => {
        try { resolve(JSON.parse(body)); } catch { resolve(body); }
      });
    });
    req.on('error', reject);
    req.write(data);
    req.end();
  });
}

function esc(str) {
  if (!str) return 'NULL';
  return "'" + String(str).replace(/'/g, "''") + "'";
}

function arr(arr) {
  return (arr.length ? `ARRAY[${arr.map(a => esc(a)).join(',')}]` : `ARRAY[]::text[]`);
}

